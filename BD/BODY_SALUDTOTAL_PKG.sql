--LISTAR CARRITO (para la vista MiCarrito.php)
PROCEDURE FIDE_CARRITO_LISTAR_SP(
P_USUARIO_SISTEMA IN FIDE_CARRITO_TB.USUARIO_SISTEMA%TYPE,
P_CURSOR OUT SYS_REFCURSOR
)IS
BEGIN
    OPEN P_CURSOR FOR
    SELECT 
        C.ID_CARRITO,
        C.CANTIDAD,
        --nombre
        CASE WHEN C.ID_SERVICIO IS NOT NULL THEN S.NOMBRE 
            ELSE M.NOMBRE_COMERCIAL || ' ' || M.PRESENTACION END AS NOMBRE_ITEM,
        --determinar precio unitario
        CASE WHEN C.ID_SERVICIO IS NOT NULL THEN S.PRECIO 
            ELSE M.PRECIO_VENTA END AS PRECIO_UNITARIO,
        --subtotal
        (C.CANTIDAD * (CASE WHEN C.ID_SERVICIO IS NOT NULL THEN S.PRECIO ELSE M.PRECIO_VENTA END)) AS SUBTOTAL,
        --IVA (13%)
        ((C.CANTIDAD * (CASE WHEN C.ID_SERVICIO IS NOT NULL THEN S.PRECIO ELSE M.PRECIO_VENTA END)) * 0.13) AS IMPUESTO,
        --Total
        ((C.CANTIDAD * (CASE WHEN C.ID_SERVICIO IS NOT NULL THEN S.PRECIO ELSE M.PRECIO_VENTA END)) * 1.13) AS TOTAL_LINEA
    FROM FIDE_CARRITO_TB C
    LEFT JOIN FIDE_SERVICIO_TB S ON C.ID_SERVICIO = S.ID_SERVICIO
    LEFT JOIN FIDE_MEDICAMENTO_TB M ON C.ID_MEDICAMENTO = M.ID_MEDICAMENTO
    WHERE C.USUARIO_SISTEMA = P_USUARIO_SISTEMA;
END FIDE_CARRITO_LISTAR_SP;


