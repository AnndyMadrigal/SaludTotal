--REALIZAR PAGO (FACTURAR)
PROCEDURE FIDE_FACTURAR_CARRITO_SP(
P_USUARIO_SISTEMA IN FIDE_CARRITO_TB.USUARIO_SISTEMA%TYPE,
P_ID_CITA IN FIDE_CITA_TB.ID_CITA%TYPE,
P_NUEVO_ID_FACTURA OUT FIDE_FACTURA_TB.ID_FACTURA%TYPE
)IS
V_ID_FACTURA FIDE_FACTURA_TB.ID_FACTURA%TYPE;
V_SUBTOTAL FIDE_FACTURA_TB.SUBTOTAL%TYPE := 0;
V_IVA FIDE_FACTURA_TB.IVA%TYPE := 0;
V_TOTAL FIDE_FACTURA_TB.MONTO_TOTAL%TYPE := 0;
V_SUCURSAL_CITA FIDE_CITA_TB.ID_SUCURSAL%TYPE;
V_LINEA NUMBER := 1;
    
    --variable para gestionar el inventario detectado
V_ID_INVENTARIO_TEMP  FIDE_INVENTARIO_TB.ID_INVENTARIO%TYPE;
    
CURSOR C_ITEMS IS
    SELECT C.ID_SERVICIO, C.ID_MEDICAMENTO, C.CANTIDAD,
        CASE WHEN C.ID_SERVICIO IS NOT NULL THEN S.PRECIO ELSE M.PRECIO_VENTA END AS PRECIO,
        CASE WHEN C.ID_SERVICIO IS NOT NULL THEN S.NOMBRE ELSE M.NOMBRE_COMERCIAL END AS CONCEPTO
    FROM FIDE_CARRITO_TB C
    LEFT JOIN FIDE_SERVICIO_TB S ON C.ID_SERVICIO = S.ID_SERVICIO
    LEFT JOIN FIDE_MEDICAMENTO_TB M ON C.ID_MEDICAMENTO = M.ID_MEDICAMENTO
    WHERE C.USUARIO_SISTEMA = P_USUARIO_SISTEMA;
        
BEGIN
--obtener la sucursal de la cita
SELECT ID_SUCURSAL INTO V_SUCURSAL_CITA FROM FIDE_CITA_TB WHERE ID_CITA = P_ID_CITA;

--INSERTAR CABECERA
INSERT INTO FIDE_FACTURA_TB (ID_CITA, FECHA_EMISION, SUBTOTAL, IVA, MONTO_TOTAL, ID_ESTADO)
VALUES (P_ID_CITA, SYSDATE, 0, 0, 0, 1)
RETURNING ID_FACTURA INTO V_ID_FACTURA;

P_NUEVO_ID_FACTURA := V_ID_FACTURA;

    --3 procesar items
FOR ITEM IN C_ITEMS LOOP
        
        -- inicializar variable temporal
V_ID_INVENTARIO_TEMP := NULL;

        --a. si es Medicamento, buscar el lote de inventario especifico en la sucursal
IF ITEM.ID_MEDICAMENTO IS NOT NULL THEN
    BEGIN
        SELECT ID_INVENTARIO INTO V_ID_INVENTARIO_TEMP
        FROM FIDE_INVENTARIO_TB
        WHERE ID_MEDICAMENTO = ITEM.ID_MEDICAMENTO 
            AND ID_SUCURSAL = V_SUCURSAL_CITA
            AND STOCK >= ITEM.CANTIDAD --verificar que alcance
            AND ROWNUM = 1; --tomar el primero disponible (FIFO simplificado)
                  
        --descontar el stock inmediatamente
        UPDATE FIDE_INVENTARIO_TB 
        SET STOCK = STOCK - ITEM.CANTIDAD
        WHERE ID_INVENTARIO = V_ID_INVENTARIO_TEMP;

    EXCEPTION WHEN NO_DATA_FOUND THEN
            --si no hay stock, lanzamos error específico
            RAISE_APPLICATION_ERROR(-20003, 'No hay stock suficiente para el medicamento en esta sucursal.');
    END;
END IF;

        --b insertar Detalle (usando ID_INVENTARIO o NULL si es servicio)
INSERT INTO FIDE_FACTURA_DETALLE_TB (ID_FACTURA, ID_LINEA, CONCEPTO, ID_INVENTARIO, ID_SERVICIO, CANTIDAD, PRECIO_UNITARIO, SUBTOTAL)
VALUES( V_ID_FACTURA, V_LINEA,  ITEM.CONCEPTO, V_ID_INVENTARIO_TEMP, ITEM.ID_SERVICIO, ITEM.CANTIDAD, ITEM.PRECIO, (ITEM.CANTIDAD * ITEM.PRECIO)
);

        V_LINEA := V_LINEA + 1;
    END LOOP;

    -- 4 calcular totales finales
    SELECT SUM(SUBTOTAL) INTO V_SUBTOTAL FROM FIDE_FACTURA_DETALLE_TB WHERE ID_FACTURA = V_ID_FACTURA;
    
    --validación por si el subtotal quedó nulo
    IF V_SUBTOTAL IS NULL THEN V_SUBTOTAL := 0; END IF;
    
    V_IVA := V_SUBTOTAL * 0.13;
    V_TOTAL := V_SUBTOTAL + V_IVA;

    UPDATE FIDE_FACTURA_TB 
    SET SUBTOTAL = V_SUBTOTAL, IVA = V_IVA, MONTO_TOTAL = V_TOTAL
    WHERE ID_FACTURA = V_ID_FACTURA;
    
    -- 5 actualizar estado de la Cita (Cerrarla)
    UPDATE FIDE_CITA_TB SET ID_ESTADO = 4 WHERE ID_CITA = P_ID_CITA;
    
    -- 6 limpiar Carrito
    DELETE FROM FIDE_CARRITO_TB WHERE USUARIO_SISTEMA = P_USUARIO_SISTEMA;
    
    COMMIT;

EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    RAISE_APPLICATION_ERROR(-20002, 'Error al facturar: ' || SQLERRM);
END FIDE_FACTURAR_CARRITO_SP;

