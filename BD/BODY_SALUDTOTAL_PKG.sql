--INSERTAR DETALLE (Calculo Automatico)
PROCEDURE FIDE_FACTURA_DETALLE_INSERT_SP(
P_ID_FACTURA IN FIDE_FACTURA_DETALLE_TB.ID_FACTURA%TYPE,
P_ID_LINEA IN FIDE_FACTURA_DETALLE_TB.ID_LINEA%TYPE,
P_ID_INVENTARIO IN FIDE_FACTURA_DETALLE_TB.ID_INVENTARIO%TYPE,
P_ID_SERVICIO IN FIDE_FACTURA_DETALLE_TB.ID_SERVICIO%TYPE,
P_CANTIDAD IN FIDE_FACTURA_DETALLE_TB.CANTIDAD%TYPE
)IS
    V_PRECIO_UNITARIO DECIMAL(12,2);
    V_SUBTOTAL_LINEA DECIMAL(12,2);
    V_CONCEPTO VARCHAR2(100);
    V_TOTAL_FACTURA DECIMAL(12,2);
    V_IVA_FACTURA DECIMAL(12,2);
BEGIN
    -- 1.OBTENER PRECIO Y CONCEPTO DE LA BD
--si en el carrito añadimos un servicio o medicamento, se verifica aqui
IF P_ID_SERVICIO IS NOT NULL THEN
    SELECT PRECIO, NOMBRE INTO V_PRECIO_UNITARIO, V_CONCEPTO 
    FROM FIDE_SERVICIO_TB WHERE ID_SERVICIO = P_ID_SERVICIO;
ELSIF P_ID_INVENTARIO IS NOT NULL THEN

    --Se hace el JOIN para llegar al precio del medicamento desde el inventario
    SELECT M.PRECIO_VENTA, M.NOMBRE_COMERCIAL || ' ' || M.PRESENTACION 
    INTO V_PRECIO_UNITARIO, V_CONCEPTO
    FROM FIDE_INVENTARIO_TB I
    JOIN FIDE_MEDICAMENTO_TB M ON I.ID_MEDICAMENTO = M.ID_MEDICAMENTO
    WHERE I.ID_INVENTARIO = P_ID_INVENTARIO;
END IF;

-- 2.CALCULAMOS SUBTOTAL DE LINEA
V_SUBTOTAL_LINEA := V_PRECIO_UNITARIO * P_CANTIDAD; --LA CANTIDAD VIENE DE LA PAGINA WEB

-- 3.INSERTAMOS DETALLE
INSERT INTO FIDE_FACTURA_DETALLE_TB(
ID_FACTURA, 
ID_LINEA, 
CONCEPTO, 
ID_INVENTARIO, 
ID_SERVICIO, 
CANTIDAD, 
PRECIO_UNITARIO, 
SUBTOTAL
)
VALUES(
P_ID_FACTURA, 
P_ID_LINEA, 
V_CONCEPTO, 
P_ID_INVENTARIO, 
P_ID_SERVICIO, 
P_CANTIDAD, 
V_PRECIO_UNITARIO, 
V_SUBTOTAL_LINEA
);

-- 4.ACTUALIZAR FACTURA PADRE
-- Sumamos todo lo que hay en detalles para esta factura
UPDATE FIDE_FACTURA_TB F
SET 
    SUBTOTAL = (SELECT SUM(SUBTOTAL) FROM FIDE_FACTURA_DETALLE_TB WHERE ID_FACTURA = P_ID_FACTURA),
    IVA = (SELECT SUM(SUBTOTAL) * 0.13 FROM FIDE_FACTURA_DETALLE_TB WHERE ID_FACTURA = P_ID_FACTURA),
    MONTO_TOTAL = (SELECT SUM(SUBTOTAL) * 1.13 FROM FIDE_FACTURA_DETALLE_TB WHERE ID_FACTURA = P_ID_FACTURA)
WHERE ID_FACTURA = P_ID_FACTURA;

COMMIT;

EXCEPTION
    WHEN OTHERS THEN 
        DBMS_OUTPUT.PUT_LINE('Error en Detalle: ' || SQLERRM);
        ROLLBACK;
END FIDE_FACTURA_DETALLE_INSERT_SP;

