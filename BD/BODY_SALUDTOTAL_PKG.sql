--AGREGAR ITEM (si ya existe, suma cantidad, si no, inserta)
PROCEDURE FIDE_CARRITO_AGREGAR_SP(
P_USUARIO_SISTEMA IN FIDE_CARRITO_TB.USUARIO_SISTEMA%TYPE,
P_ID_SERVICIO IN FIDE_CARRITO_TB.ID_SERVICIO%TYPE,
P_ID_MEDICAMENTO IN FIDE_CARRITO_TB.ID_MEDICAMENTO%TYPE
)IS
    V_CANTIDAD_ACTUAL NUMBER;
BEGIN

--primero se ve si ya existe
BEGIN
    SELECT CANTIDAD INTO V_CANTIDAD_ACTUAL
    FROM FIDE_CARRITO_TB
    WHERE USUARIO_SISTEMA = P_USUARIO_SISTEMA
        AND ((ID_SERVICIO = P_ID_SERVICIO) OR (ID_MEDICAMENTO = P_ID_MEDICAMENTO));
              
--si existe, actualizamos
    UPDATE FIDE_CARRITO_TB
    SET CANTIDAD = V_CANTIDAD_ACTUAL + 1
    WHERE USUARIO_SISTEMA = P_USUARIO_SISTEMA
    AND ((ID_SERVICIO = P_ID_SERVICIO) OR (ID_MEDICAMENTO = P_ID_MEDICAMENTO));
              
EXCEPTION WHEN NO_DATA_FOUND THEN
    --si no existe, insertamos con cantidad 1
    INSERT INTO FIDE_CARRITO_TB (USUARIO_SISTEMA, ID_SERVICIO, ID_MEDICAMENTO, CANTIDAD)
    VALUES (P_USUARIO_SISTEMA, P_ID_SERVICIO, P_ID_MEDICAMENTO, 1);
END;
        
    COMMIT;
END FIDE_CARRITO_AGREGAR_SP;

