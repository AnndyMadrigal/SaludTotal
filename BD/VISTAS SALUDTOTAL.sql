CREATE OR REPLACE VIEW FIDE_DIRECTORIO_PERSONAL_V AS
SELECT 
    P.ID_PERSONAL,
    P.NOMBRE || ' ' || P.APELLIDO_PATERNO AS NOMBRE_COMPLETO,
    R.NOMBRE_ROL AS PUESTO,
    S.NOMBRE AS "SEDE ASIGNADA",
    P.FECHA_CONTRATACION,
    CASE 
        WHEN P.ID_ESTADO = 1 THEN 'Activo'
        ELSE 'Inactivo'
    END AS ESTADO_ACTUAL
FROM FIDE_PERSONAL_TB P
JOIN FIDE_ROL_PERSONAL_TB R ON P.ID_ROL_PERSONAL = R.ID_ROL_PERSONAL
JOIN FIDE_SUCURSAL_TB S ON P.ID_SUCURSAL = S.ID_SUCURSAL;
----------------
SELECT * FROM FIDE_DIRECTORIO_PERSONAL_V;
----------------

