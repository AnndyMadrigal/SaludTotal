CREATE OR REPLACE VIEW FIDE_RESUMEN_VENTAS_SUCURSAL_V AS
SELECT 
    S.NOMBRE AS NOMBRE_SUCURSAL,
    COUNT(F.ID_FACTURA) AS "CANTIDAD FACTURAS",
    SUM(F.SUBTOTAL) AS SUBTOTAL_ACUMULADO,
    SUM(F.IVA) AS IVA_ACUMULADO,
    SUM(F.MONTO_TOTAL) AS TOTAL_GENERAL
FROM FIDE_SUCURSAL_TB S
JOIN FIDE_CITA_TB C ON S.ID_SUCURSAL = C.ID_SUCURSAL
JOIN FIDE_FACTURA_TB F ON C.ID_CITA = F.ID_CITA
WHERE F.ID_ESTADO = 1 -- Solo facturas activas
GROUP BY S.NOMBRE;
----------------
SELECT * FROM FIDE_RESUMEN_VENTAS_SUCURSAL_V;
----------------
