---  PACIENTES CON CITAS ---
CREATE OR REPLACE VIEW FIDE_PACIENTES_CON_CITAS_V AS
SELECT
    P.NOMBRE || ' ' || P.APELLIDO_PATERNO || ' ' || P.APELLIDO_MATERNO AS NOMBRE_COMPLETO,
    C.FECHA_HORA_CITA,
    PE.NOMBRE || ' ' || PE.APELLIDO_PATERNO || ' ' || PE.APELLIDO_MATERNO AS NOMBRE_MEDICO
FROM
    FIDE_PACIENTE_TB P, FIDE_CITA_TB C, FIDE_PERSONAL_TB PE
WHERE
     C.ID_PACIENTE = P.ID_PACIENTE
AND 
    C.ID_MEDICO = PE.ID_PERSONAL;
/
----------------
SELECT * FROM FIDE_PACIENTES_CON_CITAS_V;
