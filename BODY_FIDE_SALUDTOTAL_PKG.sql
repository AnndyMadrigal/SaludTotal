P_NOMBRE IN FIDE_SUCURSAL_TB.NOMBRE%TYPE,
P_ID_DIRECCION IN FIDE_SUCURSAL_TB.ID_DIRECCION%TYPE,
P_TELEFONO IN FIDE_SUCURSAL_TB.TELEFONO%TYPE,
P_ID_ESTADO IN FIDE_SUCURSAL_TB.ID_ESTADO%TYPE
)IS
    V_NUEVO_ID NUMBER; -- Variable temporal para guardar el ID
BEGIN
    
    SELECT NVL(MAX(ID_SUCURSAL), 0) + 1 INTO V_NUEVO_ID FROM FIDE_SUCURSAL_TB;

    INSERT INTO FIDE_SUCURSAL_TB(ID_SUCURSAL, NOMBRE, ID_DIRECCION, TELEFONO, ID_ESTADO)
    VALUES(V_NUEVO_ID, P_NOMBRE, P_ID_DIRECCION, P_TELEFONO, P_ID_ESTADO);
        
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Sucursal insertada con ID: ' || V_NUEVO_ID);
EXCEPTION
    WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('Error inesperado al insertar sucursal: ' || SQLERRM);
END FIDE_SUCURSAL_TB_INSERTAR_SP;

