FUNCTION FIDE_CALCULAR_VENTAS_SUCURSAL_FN(
    P_ID_SUCURSAL NUMBER
) RETURN NUMBER IS
        V_TOTAL_VENTAS NUMBER := 0;
    CURSOR C_FACTURAS IS
    SELECT F.MONTO_TOTAL 
    FROM FIDE_FACTURA_TB F
    JOIN FIDE_CITA_TB C ON F.ID_CITA = C.ID_CITA
    WHERE C.ID_SUCURSAL = P_ID_SUCURSAL AND F.ID_ESTADO = 1;
BEGIN
    FOR R_FACTURA IN C_FACTURAS LOOP
            V_TOTAL_VENTAS := V_TOTAL_VENTAS + R_FACTURA.MONTO_TOTAL;
    END LOOP;
    RETURN V_TOTAL_VENTAS;
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Error en funcion ventas: ' || SQLERRM);
        RETURN 0;
END FIDE_CALCULAR_VENTAS_SUCURSAL_FN;
