FUNCTION FIDE_ALERGIAS_PACIENTES_FN
RETURN NUMBER
IS
    V_CONTADOR NUMBER := 0;
    -- Cursor de Pacientes
    CURSOR PACIENTES IS SELECT ID_PACIENTE, NOMBRE || ' ' || APELLIDO_PATERNO AS NOMBRE_COMPLETO FROM FIDE_PACIENTE_TB;
    -- Cursor de Alergias
    CURSOR ALERGIAS IS SELECT ID_PACIENTE FROM FIDE_PACIENTE_ALERGIA_TB;
BEGIN
    FOR PACIENTE IN PACIENTES LOOP
        V_CONTADOR := 0;

        FOR ALERGIA IN ALERGIAS LOOP
            IF (ALERGIA.ID_PACIENTE = PACIENTE.ID_PACIENTE) THEN
                V_CONTADOR := V_CONTADOR + 1;
            END IF;
        END LOOP;

        DBMS_OUTPUT.PUT_LINE(
            V_CONTADOR || ' ALERGIAS REGISTRADAS PARA EL PACIENTE: ' || 
            PACIENTE.NOMBRE_COMPLETO
        );
    END LOOP;

    RETURN 1;

EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('ERROR EN FUNCION ALERGIAS: ' || SQLERRM);
        RETURN 0;
END FIDE_ALERGIAS_PACIENTES_FN;

